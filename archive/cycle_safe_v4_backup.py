def forecast_V4_user(timeline: UserTimeline, artifact_path=ARTIFACT_PATH):
    stage = getattr(timeline.profile, "self_reported_stage", LifeStage.UNKNOWN)
    cycles = timeline_cycle_lengths(timeline)

    result = {
        "user_id": timeline.profile.user_id,
        "life_stage": stage.value if hasattr(stage, "value") else str(stage),
        "forecast_available": False,
        "forecast": None,
        "message": None,
    }

    if stage == LifeStage.MENOPAUSE:
        result["message"] = (
            "Menopause stage is recorded. CycleSafe does not issue a normal next-cycle forecast; "
            "use longitudinal tracking and doctor-discussion insights instead."
        )
        return result

    if len(cycles) < MIN_HISTORY_FOR_MODEL:
        result["message"] = (
            f"At least {MIN_HISTORY_FOR_MODEL} completed cycles are needed for the forecast."
        )
        return result

    if stage == LifeStage.PERIMENOPAUSE:
        result["message"] = (
            "The self-reported perimenopause context is retained. The forecast is statistical and "
            "its uncertainty should be interpreted alongside the longitudinal record."
        )

    forecast = forecast_next_cycle(
        cycles,
        previous_context=timeline_context(timeline),
        artifact_path=artifact_path,
    )

    result["forecast_available"] = True
    result["forecast"] = forecast
    return result



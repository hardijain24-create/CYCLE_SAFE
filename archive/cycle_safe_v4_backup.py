    """
    Build the CycleSafe longitudinal health report.

    The report is designed around the actual MVP thesis:

        longitudinal record
            +
        personal baseline
            +
        recent change detection
            +
        uncertainty-aware forecasting
            +
        doctor-ready evidence

    It is informational and not diagnostic.
    """

    # ==================================================================
    # PROFILE
    # ==================================================================

    stage = timeline.profile.self_reported_stage

    stage_value = (
        stage.value
        if hasattr(stage, "value")
        else str(stage)
    )

    profile = {
        "user_id": timeline.profile.user_id,
        "age": timeline.profile.age,
        "self_reported_stage": stage_value,
    }

    # ==================================================================
    # DATA COVERAGE
    # ==================================================================

    cycle_lengths = [
        float(c.cycle_length_days)
        for c in timeline.cycles
        if c.cycle_length_days is not None
    ]

    data_coverage = {
        "cycle_records": len(cycle_lengths),
        "symptom_records": len(timeline.symptoms),
        "cycle_tracking_available": len(cycle_lengths) > 0,
        "symptom_tracking_available": len(timeline.symptoms) > 0,
    }

    # ==================================================================
    # PERSONAL BASELINE
    # ==================================================================

    baseline_section = {
        "median_days": baseline.cycle_median,
        "mean_days": baseline.cycle_mean,
        "sd_days": baseline.cycle_sd,
        "recent_median_days": baseline.recent_cycle_median,
    }

    # ==================================================================
    # CHANGE DETECTION
    # ==================================================================

    changes = []

    if patterns.cycle_change_detected:

        if patterns.cycle_change_days is not None:

            if patterns.cycle_change_days > 0:
                direction = "longer"
            else:
                direction = "shorter"

            changes.append({
                "type": "cycle_change",
                "label": "Cycle-length change",
                "detail": (
                    f"Recent cycle median is approximately "
                    f"{abs(patterns.cycle_change_days):.1f} days "
                    f"{direction} than the earlier personal baseline."
                ),
            })

        else:

            changes.append({
                "type": "cycle_change",
                "label": "Cycle-length change",
                "detail": (
                    "A recent difference from the personal "
                    "cycle baseline was detected."
                ),
            })

    if patterns.variability_change_detected:

        changes.append({
            "type": "variability",
            "label": "Cycle variability",
            "detail": (
                "Recent cycle lengths appear more variable "
                "than the earlier recorded pattern."
            ),
        })

    if patterns.recurring_symptoms:

        changes.append({
            "type": "recurring_symptoms",
            "label": "Repeated symptoms",
            "detail": (
                ", ".join(patterns.recurring_symptoms)
            ),
        })

    # NOTE:
    # We intentionally do not automatically describe a symptom as

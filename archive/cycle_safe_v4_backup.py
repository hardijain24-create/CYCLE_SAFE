def build_winning_insight(baseline, patterns, forecast, stage=None):
    messages = []
    messages.append("PERSONAL BASELINE")

    if baseline.cycle_median is not None:
        messages.append(f"Historical median: {baseline.cycle_median:.1f} days.")
        if baseline.recent_cycle_median is not None:
            messages.append(f"Recent median: {baseline.recent_cycle_median:.1f} days.")
        if baseline.cycle_sd is not None:
            messages.append(f"Historical variability: {baseline.cycle_sd:.1f} days.")
    else:
        messages.append("No cycle-length baseline is available from the recorded history.")

    if getattr(baseline, "wellbeing_summary", None):
        wellbeing_parts = []
        for name, label in [("sleep_quality", "sleep"), ("mood", "mood"), ("energy", "energy")]:
            item = baseline.wellbeing_summary.get(name, {})
            recent = item.get("recent_mean")
            historical = item.get("historical_mean")
            if recent is not None:
                if historical is not None:
                    delta = recent - historical
                    direction = "higher" if delta > 0.05 else "lower" if delta < -0.05 else "similar"
                    wellbeing_parts.append(f"{label}: recent {recent:.1f}/5 vs historical {historical:.1f}/5 ({direction})")
                else:
                    wellbeing_parts.append(f"{label}: recent {recent:.1f}/5")
        if wellbeing_parts:
            messages.append("Wellbeing records: " + "; ".join(wellbeing_parts) + ".")

    messages.append("")
    messages.append("OBSERVED CHANGES")

    if patterns.cycle_change_detected and patterns.cycle_change_days is not None:
        direction = "longer" if patterns.cycle_change_days > 0 else "shorter"
        messages.append(
            f"Recent cycle median is approximately {abs(patterns.cycle_change_days):.1f} days {direction} than the earlier personal baseline."
        )
    elif patterns.cycle_change_detected:
        messages.append("A recent cycle-timing difference was detected relative to the earlier baseline.")

    if patterns.variability_change_detected:
        messages.append("Recent cycle variability is higher than the earlier personal baseline.")
    if patterns.recurring_symptoms:
        messages.append("Repeatedly recorded symptoms: " + ", ".join(patterns.recurring_symptoms) + ".")
    if patterns.rising_symptoms:
        messages.append("A later-timeline symptom-frequency signal was observed for: " + ", ".join(patterns.rising_symptoms) + ".")

    if not (patterns.cycle_change_detected or patterns.variability_change_detected or patterns.recurring_symptoms or patterns.rising_symptoms):
        messages.append("No major change signal was detected in the available recorded history.")

    messages.append("")
    messages.append("FORECAST + UNCERTAINTY")

    if forecast.predicted_cycle_length_days is not None:
        messages.append(f"Estimated next cycle: {forecast.predicted_cycle_length_days:.1f} days.")
        if forecast.lower_80_days is not None and forecast.upper_80_days is not None:
            messages.append(f"80% estimated window: {forecast.lower_80_days:.1f}–{forecast.upper_80_days:.1f} days.")
        if forecast.lower_90_days is not None and forecast.upper_90_days is not None:
            messages.append(f"90% estimated window: {forecast.lower_90_days:.1f}–{forecast.upper_90_days:.1f} days.")
        if forecast.predicted_absolute_error_days is not None:
            messages.append(f"Expected absolute error: approximately {forecast.predicted_absolute_error_days:.1f} days.")
        messages.append("These ranges summarize historical forecasting error; they are not clinical risk ranges or guarantees.")
    else:
        messages.append("No next-cycle forecast was generated for this profile.")

    messages.append("")
    messages.append("MODEL CONTEXT")
    stage_value = getattr(stage, "value", str(stage)) if stage is not None else "unknown"
    messages.append(f"Self-reported life-stage context: {stage_value}.")
    messages.append("The recorded life-stage label is not independently diagnosed by CycleSafe.")

    messages.append("")
    messages.append("BRING THIS TO YOUR DOCTOR")
    points = []
    if patterns.cycle_change_detected:
        points.append("recent change in cycle timing")
    if patterns.variability_change_detected:
        points.append("change in cycle-to-cycle variability")
    if patterns.recurring_symptoms:
        points.append("repeated symptoms: " + ", ".join(patterns.recurring_symptoms))
    if patterns.rising_symptoms:
        points.append("later-timeline symptom-frequency signal: " + ", ".join(patterns.rising_symptoms))
    if forecast.predicted_cycle_length_days is not None:
        points.append("forecast estimate and uncertainty window")
    if points:
        for p in points:
            messages.append("• Discuss " + p + ".")
    else:
        messages.append("Continue longitudinal tracking to strengthen the personal baseline.")

    messages.append("")
    messages.append("IMPORTANT")
    messages.append("CycleSafe summarizes recorded history and statistical forecasts. It does not diagnose a condition, determine reproductive stage, or replace clinical evaluation.")

    return CycleSafeInsight(
        title="CycleSafe Longitudinal Insight",
        body="\n".join(messages),
        category="longitudinal_pattern",
        informational=True,
    )



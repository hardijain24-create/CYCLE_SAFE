class FeatureEngineV4(FeatureEngine):
    """Chronological, evidence-first personal feature engine."""

    @staticmethod
    def cycle_lengths(timeline):
        ordered = sorted(
            timeline.cycles,
            key=lambda c: c.start_date,
        )
        return [
            float(c.cycle_length_days)
            for c in ordered
            if c.cycle_length_days is not None
            and math.isfinite(float(c.cycle_length_days))
        ]

    @staticmethod
    def ordered_symptoms(timeline):
        return sorted(
            timeline.symptoms,
            key=lambda s: s.record_date,
        )

    @staticmethod
    def ordered_wellbeing(timeline):
        return sorted(
            timeline.wellbeing,
            key=lambda w: w.record_date,
        )

    @staticmethod
    def _mean_or_none(values):
        values = [float(v) for v in values if v is not None and math.isfinite(float(v))]
        return float(np.mean(values)) if values else None

    @classmethod
    def build_personal_baseline(cls, timeline, recent_n=3):
        lengths = cls.cycle_lengths(timeline)
        recent = lengths[-recent_n:] if len(lengths) >= recent_n else lengths

        # Baseline is deliberately the EARLIER history when enough cycles exist.
        # This prevents recent cycles from contaminating the comparison baseline.
        if len(lengths) >= recent_n + 3:
            historical = lengths[:-recent_n]
        else:
            historical = lengths

        cycle_mean = mean(historical) if historical else None
        cycle_median = median(historical) if historical else None
        cycle_sd = (
            float(np.std(historical, ddof=1))
            if len(historical) > 1
            else None
        )

        recent_median = median(recent) if recent else None

        severity_map = {
            SymptomSeverity.NONE: 0.0,
            SymptomSeverity.MILD: 1.0,
            SymptomSeverity.MODERATE: 2.0,
            SymptomSeverity.SEVERE: 3.0,
        }

        symptom_frequency = {}
        severity_values = {}
        for s in cls.ordered_symptoms(timeline):
            symptom_frequency[s.symptom] = symptom_frequency.get(s.symptom, 0.0) + 1.0
            severity_values.setdefault(s.symptom, []).append(severity_map[s.severity])

        severity_mean = {
            symptom: float(np.mean(values))
            for symptom, values in severity_values.items()
        }

        wellbeing = cls.ordered_wellbeing(timeline)
        wellbeing_summary = {}
        for field_name in ["sleep_quality", "mood", "energy"]:
            all_values = [getattr(w, field_name) for w in wellbeing]
            recent_values = [getattr(w, field_name) for w in wellbeing[-recent_n:]]
            wellbeing_summary[field_name] = {
                "historical_mean": cls._mean_or_none(all_values),
                "recent_mean": cls._mean_or_none(recent_values),
            }

        return PersonalBaseline(
            cycle_median=cycle_median,
            cycle_mean=cycle_mean,
            cycle_sd=cycle_sd,
            recent_cycle_median=recent_median,
            cycle_variability=cycle_sd,
            symptom_frequency=symptom_frequency,
            symptom_severity_mean=severity_mean,
            wellbeing_summary=wellbeing_summary,
            baseline_cycle_count=len(historical),
            recent_cycle_count=len(recent),
        )


class PatternEngineV4(PatternEngine):
    """Descriptive change detection against an earlier personal baseline."""

    def analyze(
        self,
        baseline,
        timeline,
        recent_n=3,
        cycle_change_threshold_days=3.0,
        variability_threshold=1.5,
    ):
        lengths = FeatureEngineV4.cycle_lengths(timeline)
        recent = lengths[-recent_n:] if len(lengths) >= recent_n else lengths

        cycle_change = None
        cycle_change_detected = False
        if baseline.cycle_median is not None and recent:
            cycle_change = float(median(recent) - baseline.cycle_median)
            cycle_change_detected = abs(cycle_change) >= cycle_change_threshold_days

        recent_sd = None
        variability_change_detected = False
        if len(recent) > 1 and baseline.cycle_sd is not None:
            recent_sd = float(np.std(recent, ddof=1))
            variability_change_detected = (recent_sd - baseline.cycle_sd) >= variability_threshold

        symptoms = FeatureEngineV4.ordered_symptoms(timeline)
        recurring_symptoms = [
            symptom for symptom, count in baseline.symptom_frequency.items()
            if count >= 2
        ]

        rising_symptoms = []
        if len(symptoms) >= 4:
            midpoint = len(symptoms) // 2
            first = symptoms[:midpoint]
            second = symptoms[midpoint:]
            first_counts = {}
            second_counts = {}
            for s in first:
                first_counts[s.symptom] = first_counts.get(s.symptom, 0) + 1
            for s in second:
                second_counts[s.symptom] = second_counts.get(s.symptom, 0) + 1
            for symptom, count in second_counts.items():
                if count > first_counts.get(symptom, 0):
                    rising_symptoms.append(symptom)

        notes = []
        if cycle_change_detected:
            notes.append("Recent cycle timing differs from the earlier personal baseline.")
        if variability_change_detected:
            notes.append("Recent cycle variability is higher than the earlier baseline.")
        if recurring_symptoms:
            notes.append("Some symptoms have been recorded repeatedly.")
        if rising_symptoms:
            notes.append("Some symptoms occur more frequently in the later recorded timeline.")

        return PatternSummary(
            cycle_change_detected=cycle_change_detected,
            cycle_change_days=cycle_change,
            variability_change_detected=variability_change_detected,
            recurring_symptoms=recurring_symptoms,
            rising_symptoms=rising_symptoms,
            notes=notes,
        )



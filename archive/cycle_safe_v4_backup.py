def _history_group(value):

    try:
        value = float(value)
    except Exception:
        return "unknown"

    if value < 5:
        return "3-4"

    if value < 7:
        return "5-6"

    if value < 10:
        return "7-9"

    if value < 15:
        return "10-14"

    return "15+"


def _variability_group(series):

    numeric = pd.to_numeric(
        series,
        errors="coerce",
    )

    ranked = numeric.rank(
        method="first"
    )

    try:

        return pd.qcut(
            ranked,
            q=3,
            labels=[
                "low",
                "medium",
                "high",
            ],
        )

    except Exception:

        return pd.Series(
            [
                "unknown"
            ] * len(series),
            index=series.index,
        )



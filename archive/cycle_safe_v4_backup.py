# 4. PAIRED USER-CLUSTERED BOOTSTRAP
# =============================================================================

def paired_mae_difference_ci(
    actual,
    prediction_a,
    prediction_b,
    user_ids,
    n_boot=RESEARCH_BOOTSTRAP_REPS,
    seed=RESEARCH_RANDOM_STATE,
):
    """
    Paired user-clustered bootstrap.

    Difference:

        MAE(A) - MAE(B)

    Negative:
        A has lower MAE.

    Positive:
        A has higher MAE.
    """

    comparison = pd.DataFrame(
        {
            "user_id": np.asarray(
                user_ids
            ),
            "actual": np.asarray(
                actual,
                dtype=float,
            ),
            "prediction_a": np.asarray(
                prediction_a,
                dtype=float,
            ),
            "prediction_b": np.asarray(
                prediction_b,
                dtype=float,
            ),
        }
    )

    comparison = comparison.replace(
        [np.inf, -np.inf],
        np.nan,
    )

    comparison = comparison.dropna(
        subset=[
            "user_id",
            "actual",
            "prediction_a",
            "prediction_b",
        ]
    )

    if comparison.empty:

        return {
            "mae_a": np.nan,
            "mae_b": np.nan,
            "difference": np.nan,
            "lower_95": np.nan,
            "upper_95": np.nan,
            "n_observations": 0,
            "n_users": 0,
        }

    comparison[
        "error_a"
    ] = (
        comparison["actual"]
        - comparison["prediction_a"]
    ).abs()

    comparison[
        "error_b"
    ] = (
        comparison["actual"]
        - comparison["prediction_b"]
    ).abs()

    mae_a = comparison[
        "error_a"
    ].mean()

    mae_b = comparison[
        "error_b"
    ].mean()

    observed_difference = (
        mae_a - mae_b
    )

    user_codes, unique_users = pd.factorize(
        comparison["user_id"],
        sort=False,
    )

    error_a = comparison[
        "error_a"
    ].to_numpy(
        dtype=float
    )

    error_b = comparison[
        "error_b"
    ].to_numpy(
        dtype=float
    )

    n_users = len(
        unique_users
    )

    user_indices = [
        np.flatnonzero(
            user_codes == i
        )
        for i in range(n_users)
    ]

    rng = np.random.default_rng(
        seed
    )

    bootstrap_differences = np.empty(
        n_boot,
        dtype=float,
    )

    for boot_index in range(
        n_boot
    ):

        sampled_users = rng.integers(
            0,
            n_users,
            size=n_users,
        )

        sampled_indices = np.concatenate(
            [
                user_indices[user_index]
                for user_index in sampled_users
            ]
        )

        bootstrap_differences[
            boot_index
        ] = (
            np.mean(
                error_a[
                    sampled_indices
                ]
            )
            -
            np.mean(
                error_b[
                    sampled_indices
                ]
            )
        )

    return {
        "mae_a": float(mae_a),
        "mae_b": float(mae_b),
        "difference": float(
            observed_difference
        ),
        "lower_95": float(
            np.quantile(
                bootstrap_differences,
                0.025,
            )
        ),
        "upper_95": float(
            np.quantile(
                bootstrap_differences,
                0.975,
            )
        ),
        "n_observations": int(
            len(comparison)
        ),
        "n_users": int(
            n_users
        ),
    }



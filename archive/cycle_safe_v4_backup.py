def _find_first_existing(frame, candidates):
    """
    Return the first candidate column present in a DataFrame.
    """

    for column in candidates:
        if column in frame.columns:
            return column

    return None


def _find_actual_column(frame):
    """
    Identify actual cycle-length column.
    """

    candidates = [
        "actual",
        "actual_cycle_length",
        "cycle_length",
        "target",
        "y_true",
    ]

    column = _find_first_existing(
        frame,
        candidates,
    )

    if column is None:
        raise KeyError(
            "Could not identify actual cycle-length column.\n"
            f"Available columns: {list(frame.columns)}"
        )

    return column


def _find_user_column(frame):
    """
    Identify participant/user column.
    """

    candidates = [
        "user_id",
        "participant_id",
        "participant",
        "user",
    ]

    column = _find_first_existing(
        frame,
        candidates,
    )

    if column is None:
        raise KeyError(
            "Could not identify user column.\n"
            f"Available columns: {list(frame.columns)}"
        )

    return column


def _selected_prediction_column(
    frame,
    model_name,
):
    """
    Locate a model prediction column in OOF data.
    """

    candidates = [
        model_name,
        f"{model_name}_prediction",
        f"pred_{model_name}",
        f"prediction_{model_name}",
        f"{model_name}_pred",
    ]

    column = _find_first_existing(
        frame,
        candidates,
    )

    if column is not None:
        return column

    lower_map = {
        str(column).lower(): column
        for column in frame.columns
    }

    for candidate in candidates:

        if candidate.lower() in lower_map:
            return lower_map[
                candidate.lower()
            ]

    return None



# STRATIFIED ERROR ANALYSIS
# =============================================================================

def error_by_history_and_variability(
    oof: pd.DataFrame,
    prediction_column: str,
) -> pd.DataFrame:

    x = oof.copy()

    x["history_group"] = pd.cut(
        x["history_count"],
        bins=[2, 4, 6, 9, 14, np.inf],
        labels=["3-4", "5-6", "7-9", "10-14", "15+"],
        include_lowest=True,
    )

    # Use development OOF variability itself, not the final test.
    x["variability_group"] = pd.qcut(
        x["cv_5"].rank(method="first"),
        q=3,
        labels=["low", "medium", "high"],
    )

    x["abs_error"] = np.abs(
        x["actual"] - x[prediction_column]
    )

    result = (
        x.groupby(
            ["history_group", "variability_group"],
            observed=False,
        )
        .agg(
            observations=("abs_error", "size"),
            mae=("abs_error", "mean"),
            median_abs_error=("abs_error", "median"),
        )
        .reset_index()
    )

    return result



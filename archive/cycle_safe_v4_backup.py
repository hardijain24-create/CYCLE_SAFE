# 3. FAST USER-CLUSTERED BOOTSTRAP
# =============================================================================

def _cluster_bootstrap_metric(
    frame,
    user_col,
    value_col,
    statistic=np.mean,
    n_boot=RESEARCH_BOOTSTRAP_REPS,
    seed=RESEARCH_RANDOM_STATE,
):
    """
    User-clustered bootstrap.

    All rows belonging to a participant are kept together
    when that participant is resampled.
    """

    if frame is None or len(frame) == 0:

        return {
            "estimate": np.nan,
            "lower_95": np.nan,
            "upper_95": np.nan,
            "n_observations": 0,
            "n_users": 0,
        }

    data = frame[
        [
            user_col,
            value_col,
        ]
    ].copy()

    data[value_col] = pd.to_numeric(
        data[value_col],
        errors="coerce",
    )

    data = data.dropna(
        subset=[
            user_col,
            value_col,
        ]
    )

    if data.empty:

        return {
            "estimate": np.nan,
            "lower_95": np.nan,
            "upper_95": np.nan,
            "n_observations": 0,
            "n_users": 0,
        }

    user_codes, unique_users = pd.factorize(
        data[user_col],
        sort=False,
    )

    values = data[
        value_col
    ].to_numpy(
        dtype=float
    )

    n_users = len(
        unique_users
    )

    if n_users == 0:

        return {
            "estimate": np.nan,
            "lower_95": np.nan,
            "upper_95": np.nan,
            "n_observations": 0,
            "n_users": 0,
        }

    # Precompute rows belonging to each user.
    user_indices = [
        np.flatnonzero(
            user_codes == i
        )
        for i in range(n_users)
    ]

    observed = float(
        statistic(values)
    )

    rng = np.random.default_rng(
        seed
    )

    bootstrap_values = np.empty(
        n_boot,
        dtype=float,
    )

    for boot_index in range(
        n_boot
    ):

        sampled_users = rng.integers(
            0,
            n_users,
            size=n_users,
        )

        sampled_indices = np.concatenate(
            [
                user_indices[user_index]
                for user_index in sampled_users
            ]
        )

        bootstrap_values[
            boot_index
        ] = statistic(
            values[
                sampled_indices
            ]
        )

    return {
        "estimate": observed,
        "lower_95": float(
            np.quantile(
                bootstrap_values,
                0.025,
            )
        ),
        "upper_95": float(
            np.quantile(
                bootstrap_values,
                0.975,
            )
        ),
        "n_observations": int(
            len(values)
        ),
        "n_users": int(
            n_users
        ),
    }



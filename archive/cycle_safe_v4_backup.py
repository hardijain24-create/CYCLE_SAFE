# PATTERN ENGINE
# ======================================================================

class PatternEngine:

    """
    Detects longitudinal changes.

    This is descriptive pattern detection only.
    It does not diagnose conditions.
    """

    def analyze(
        self,
        baseline: PersonalBaseline,
        timeline: UserTimeline,
        recent_n: int = 3,
        cycle_change_threshold_days: float = 3.0,
        variability_threshold: float = 1.5,
    ) -> PatternSummary:

        lengths = FeatureEngine.cycle_lengths(timeline)

        recent = (
            lengths[-recent_n:]
            if len(lengths) >= recent_n
            else lengths
        )

        # --------------------------------------------------------------
        # Cycle change
        # --------------------------------------------------------------

        cycle_change = None
        cycle_change_detected = False

        if baseline.cycle_median is not None and recent:

            cycle_change = (
                median(recent)
                - baseline.cycle_median
            )

            cycle_change_detected = (
                abs(cycle_change)
                >= cycle_change_threshold_days
            )

        # --------------------------------------------------------------
        # Variability change
        # --------------------------------------------------------------

        recent_sd = None
        variability_change_detected = False

        if len(recent) > 1:

            recent_mean = mean(recent)

            recent_sd = math.sqrt(
                sum(
                    (x - recent_mean) ** 2
                    for x in recent
                )
                / (len(recent) - 1)
            )

            if baseline.cycle_sd is not None:

                variability_change_detected = (
                    recent_sd - baseline.cycle_sd
                    >= variability_threshold
                )

        # --------------------------------------------------------------
        # Recurring symptoms
        # --------------------------------------------------------------

        recurring_symptoms = [
            symptom
            for symptom, count
            in baseline.symptom_frequency.items()
            if count >= 2
        ]

        # --------------------------------------------------------------
        # Rising symptom frequency
        # --------------------------------------------------------------

        rising_symptoms = []

        if len(timeline.symptoms) >= 4:

            midpoint = len(timeline.symptoms) // 2

            first = timeline.symptoms[:midpoint]
            second = timeline.symptoms[midpoint:]

            first_counts: Dict[str, int] = {}
            second_counts: Dict[str, int] = {}

            for s in first:
                first_counts[s.symptom] = (
                    first_counts.get(s.symptom, 0) + 1
                )

            for s in second:
                second_counts[s.symptom] = (
                    second_counts.get(s.symptom, 0) + 1
                )

            for symptom, count in second_counts.items():

                if count > first_counts.get(symptom, 0):
                    rising_symptoms.append(symptom)

        # --------------------------------------------------------------
        # Notes
        # --------------------------------------------------------------

        notes = []

        if cycle_change_detected:
            notes.append(
                "Recent cycle length differs from the personal baseline."
            )

        if variability_change_detected:
            notes.append(
                "Recent cycle variability is higher than the historical baseline."
            )

        if recurring_symptoms:
            notes.append(
                "Some symptoms have been recorded repeatedly."
            )

        if rising_symptoms:
            notes.append(
                "Some symptoms appear more frequently in the recent timeline."
            )

        return PatternSummary(
            cycle_change_detected=cycle_change_detected,
            cycle_change_days=cycle_change,
            variability_change_detected=variability_change_detected,
            recurring_symptoms=recurring_symptoms,
            rising_symptoms=rising_symptoms,
            notes=notes,
        )


# =============================================================================
# EMPIRICAL UNCERTAINTY CALIBRATION
# =============================================================================

def conformal_radius(
    actual,
    predicted,
    alpha: float,
) -> float:
    residuals = np.abs(
        np.asarray(actual, dtype=float)
        - np.asarray(predicted, dtype=float)
    )
    residuals = residuals[np.isfinite(residuals)]

    if len(residuals) == 0:
        return np.nan

    # Finite-sample conformal-style quantile.
    q = np.ceil((len(residuals) + 1) * (1 - alpha)) / len(residuals)
    q = min(max(q, 0.0), 1.0)

    return float(np.quantile(residuals, q, method="higher"))


def interval_score(actual, lower, upper, alpha: float) -> float:
    """Mean interval score; lower is better.

    Combines interval width with penalties for observations outside the
    interval. It is evaluated on the untouched final test only after
    calibration has been fixed using development OOF residuals.
    """
    actual = np.asarray(actual, dtype=float)
    lower = np.asarray(lower, dtype=float)
    upper = np.asarray(upper, dtype=float)
    score = (upper - lower).copy()
    below = actual < lower
    above = actual > upper
    score[below] += (2.0 / alpha) * (lower[below] - actual[below])
    score[above] += (2.0 / alpha) * (actual[above] - upper[above])
    return float(np.mean(score))


def interval_report(
    actual,
    predicted,
    radius80,
    radius90,
) -> Dict[str, float]:

    actual = np.asarray(actual, dtype=float)
    predicted = np.asarray(predicted, dtype=float)

    lo80 = predicted - radius80
    hi80 = predicted + radius80
    lo90 = predicted - radius90
    hi90 = predicted + radius90

    return {
        "80_coverage": float(
            np.mean((actual >= lo80) & (actual <= hi80))
        ),
        "90_coverage": float(
            np.mean((actual >= lo90) & (actual <= hi90))
        ),
        "80_mean_width": float(np.mean(hi80 - lo80)),
        "90_mean_width": float(np.mean(hi90 - lo90)),
        "80_interval_score": interval_score(actual, lo80, hi80, alpha=0.20),
        "90_interval_score": interval_score(actual, lo90, hi90, alpha=0.10),
    }


